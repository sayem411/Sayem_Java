public class operators {
    public static void main(String[] args) {
        int a=1;
        int b =2;
        int sum = a+b;
        int diff = a-b;
        int mul = a*b;
        int div = a/b;
        int mod = a%b;
        System.out.println(sum);
        System.out.println(diff);
        System.out.println(mul);
        System.out.println(div);
        System.out.println(mod);

        double c=5;
        double d =3;
        double modulo=c%d;
        System.out.println(modulo);
    }
}
